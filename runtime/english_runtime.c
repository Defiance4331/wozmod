static void halfway(float *point, const float *prev, const float *now)
{
    u32 k;
    if (near3(prev, now))
        for (k = 0; k < 3; k++)
            point[k] += (prev[k] - now[k]) * 0.5f;
}



static void head_point(float *point, const float *bone)
{
    u32 i = head_of;
    if (!hfr_busy || i >= CHARACTERS)
        return;
    if (!extra) {
        CopyMemory(head_prev[i], bone, sizeof *head_prev);
        head_stamp[i] = hfr_stats.frames + 1;
    } else if (have_prev && head_stamp[i] == hfr_stats.frames)
        halfway(point, head_prev[i], bone);
}


static void marker_point(float *point)
{
    u32 i;
    if (!extra || !have_prev)
        return;
    for (i = 0; i < CHARACTERS; i++)
        if (CHARACTER_AT(i)[0] == point[0] && CHARACTER_AT(i)[2] == point[2]) {
            halfway(point, character_prev[i], CHARACTER_AT(i));
            return;
        }
}

static long __stdcall vs_const(void *device, u32 reg, const float *data, u32 count)
{
    u32 n = upload_index, m = UPLOADS, i;
#ifdef ENRT_TEST
    if (hfr_busy && count <= 256 && extra && have_prev && count % 3 == 0 && !(hfr_prof.knobs & 1)) {
        u32 t = (u32)__rdtsc();
        m = pair_find(&pair_prev, n, reg << 16 | count, data, count, &prof_gaps);
        hfr_prof.tick[hfr_prof.next % PROF_TICKS].pair_cycles += (u32)__rdtsc() - t;
    }
#else
    if (hfr_busy && count <= 256 && extra && have_prev && count % 3 == 0) {
        u32 gaps = 0;
        m = pair_find(&pair_prev, n, reg << 16 | count, data, count, &gaps);
    }
#endif
    trace(1, reg, count, extra, (u32)__builtin_return_address(0), m, 0, data, count * 16);
    if (!hfr_busy || count > 256)
        return REAL(vs_const_fn, device, SLOT_VS_CONST)(device, reg, data, count);
    upload_index++;
    if (!extra) {
        if (n < UPLOADS) {
            upload_key[n] = reg << 16 | count;
            for (i = 0; i < count * 4; i++)
                uploads[n][i] = data[i];
        }
    } else if (count % 3 == 0) {
        if (m < upload_count) {
            for (i = 0; i < count * 4; i++)
                lerped[i] = (uploads[m][i] + data[i]) * 0.5f;
            data = lerped;
            hfr_stats.lerped++;
        } else
            hfr_stats.mismatched++;
    }
    return REAL(vs_const_fn, device, SLOT_VS_CONST)(device, reg, data, count);
}

static int vtable_write(void **at, void *value)
{
    DWORD old;
    if (!VirtualProtect(at, 4, PAGE_READWRITE, &old))
        return 0;
    *at = value;
    VirtualProtect(at, 4, old, &old);
    return 1;
}

/* fn into the slot of the object's vtable, once per vtable (device_hooks.h) */
static void hook_slot(void *object, u32 slot, void *fn)
{
    if (!hook_put(&hooks, object, slot, fn, vtable_write))
        note("refused: could not hook vtable slot", slot);
}

