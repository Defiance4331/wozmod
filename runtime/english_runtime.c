#define SQUAD_FLAGS(s) (*(volatile u32 *)((s) + 0x80))
#define SQUAD_ARMY(s) ((s)[0x77])  /* 0 the player's side, 1 the enemy, 2 an ally (the player's side) */
#define SQUAD_ON_FIELD 0x20000
