static void note(const char *s, u32 value)
{
    char line[160], *p = line;
    DWORD written;
    while (*s && p < line + 140)
        *p++ = *s++;
    if (value) {
        *p++ = ' ', *p++ = '0', *p++ = 'x';
        p = put_hex(p, value, 8);
    }
    *p++ = '\r', *p++ = '\n';
    if (runtime_log != INVALID_HANDLE_VALUE)
        WriteFile(runtime_log, line, p - line, &written, 0);
}

