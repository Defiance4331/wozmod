static const char *wrap(const char *s, u32 width, char *out, u32 size)
{
    char *o = out, *line = out, *space = 0;
    if (!s || !*s || len(s) >= size)
        return s;
    while (*s) {
        u8 c = *s;
        char *at = o;
        *o++ = *s++;
        if ((c >= 0x81 && c <= 0x9f) || c >= 0xe0)
            if (*s)
                *o++ = *s++;

        if (c == '[' && s[0] && s[1])
            *o++ = *s++, *o++ = *s++;
        *o = 0;
        if (c == '\n')
            line = o, space = 0;
        else if (c == ' ')
            space = at > line ? at : 0;
        else if (space && measure(line) >= width)
            *space = '\n', line = space + 1, space = 0;
    }
    return out;
}

/* table.bin's part slots (wozmod.text.build.PART_TABLES): the English of every name part, then of every weapon,
   and after them the slots a per-index override gives. One stock string can fill several slots (two officers' names
   spelled alike, two weapons named alike), so an override is served by the slot's own stock pointer. */
#define NAMES ((const u32 *)((const u8 *)enrt_table + enrt_table[1]))
#define OVERRIDES (NAMES + 1 + NAMES[0])
#define NAME_PARTS 890
#define WEAPON_PART(i) (*(const char *const *)(0x6FA5F8 + 8 * (i)))

static const char *part(u32 i)
{
    return i < NAMES[0] && NAMES[1 + i] ? (const char *)enrt_table + NAMES[1 + i] : NAME_PART(i);
}


static u32 part_index(u32 p)
{
    u32 i;
    for (i = 0; i < NAME_PARTS && i < NAMES[0]; i++)
        if ((u32)NAME_PART(i) == p)
            return i;
    return -1;
}


static const char *overridden_part(const char *s)
{
    u32 i, slot;
    for (i = 0; i < OVERRIDES[0]; i++) {
        slot = OVERRIDES[1 + i];
        if ((slot < NAME_PARTS ? NAME_PART(slot) : WEAPON_PART(slot - NAME_PARTS)) == s)
            return (const char *)enrt_table + NAMES[1 + slot];
    }
    return 0;
}


static int prefix(const char *s)
{
    u32 n = len(s);
    return n && s[n - 1] == ' ';
}



static char *compose(char *dst, u32 surname, u32 given)
{
    const char *a = part(surname), *b = part(given);
    if (surname == given)
        copy(dst, a);
    else if (prefix(a))
        copy(copy(dst, a), b);
    else {
        char *d = copy(dst, b);
        *d++ = ' ';
        copy(d, a);
    }
    return dst;
}


static u32 name_cells(u32 surname, u32 given)
{
    char name[96];
    return (width24(compose(name, surname, given)) + 23) / 24;
}

