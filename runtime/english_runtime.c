static u32 stack_calls(const u32 *sp, u32 *out)
{
    u32 i, n = 0;
    for (i = 0; i < 256 && n < 16; i++)
        if (sp[i] > 0x401006 && sp[i] < 0x6C0000
            && (((const u8 *)sp[i])[-5] == 0xE8 || ((const u8 *)sp[i])[-2] == 0xFF || ((const u8 *)sp[i])[-3] == 0xFF
                || ((const u8 *)sp[i])[-6] == 0xFF))
            out[n++] = sp[i];
    return n;
}
