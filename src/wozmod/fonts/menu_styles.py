def style_for(style: str, *, role: str | None = None) -> dict:

    if style not in STYLES:
        raise ValueError(f"unknown menu style: {style!r}")
    if role in DREAM_CARD_POSITIONS and style in {"banner.large", "banner.small"}:
        result = deepcopy(DREAM_CARD_STYLE)
        baseline, lines = DREAM_CARD_POSITIONS[role]
        cap = result["cap"]


        result["gradient"] = [
            [(y - (baseline - cap)) * 20 / cap, colour]
            for y, colour in DREAM_CARD_GRADIENTS[lines]
        ]
        return result
    result = deepcopy(STYLES[style])
    if role is not None:
        variants = ROLE_VARIANTS.get(style, {})
        if role not in variants:
            raise ValueError(f"unknown menu role {role!r} for style {style!r}")
        override = deepcopy(variants[role])


        if "fill" in override and not {"gradient", "bands"} & override.keys():
            result.pop("gradient", None)
            result.pop("bands", None)
        result.update(override)
    return result
