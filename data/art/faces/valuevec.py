import importlib.util
from pathlib import Path


def _face(name, metrics, params, tune, bearings, space, sets):
    spec = importlib.util.spec_from_file_location(f"{__package__}.valuevec_{name}", Path(__file__).with_name("headervec.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    params = dict(params)
    if "W" in params:
        w = params["W"]
        params["V"] = dict(xl=w["x1"], wl=w["w1"], xr=w["x4"] - w["v2"] + w["v1"], wr=w["w4"], xv=w["v1"],
                           wv=w["wv"])
    m.__dict__.update(metrics, SLANT=0.0, PARAMS=params, TUNE=dict(tune), BEARINGS=bearings, SPACE=space,
                      SETS=sets)
    m.BUILD = {ch: m.BUILD[ch] for ch in params}
    m.BUILD_SET = "".join(sorted(m.BUILD))
    base_layer = m.layer

    def layer(ch, p=None, slant=None):
        q = m.PARAMS[ch] if p is None else p
        vt, vb = q.get("vt", 0.0), q.get("vb", 0.0)


        overrides = {k[1:].upper(): v for k, v in q.items() if k in ("_stem", "_bar", "_serif", "_sx", "_brk")}
        saved = {k: getattr(m, k) for k in overrides}
        try:
            m.__dict__.update(overrides)
            l = base_layer(ch, p, 0.0)
        finally:
            m.__dict__.update(saved)
        if vt or vb:
            l.transform(m.psMat.scale(1.0, (m.CAP - vt - vb) / m.CAP))
            l.transform(m.psMat.translate(0.0, vb * m.U))
        sl = m.SLANT if slant is None else slant
        if sl:
            l.transform(m.psMat.skew(m.math.atan(sl)))
        return l

    m.layer, m.base_layer = layer, base_layer
    return m


